const char note_names[] = "C-C#D-D#E-F-F#G-G#A-A#B-";

/* 0 below C-0, else 1 + the note nearest to the frequency register f */
unsigned char note_index(unsigned int f)
{
    const unsigned int *t = t_ntsc ? note_ntsc : note_pal;
    unsigned char lo = 0, hi = 96, mid;
    while (lo < hi) {                   /* the boundaries <= f */
        mid = (lo + hi) >> 1;
        if (f >= t[mid])
            lo = mid + 1;
        else
            hi = mid;
    }
    return lo;
}

/* note n (note_index's) as "A-4" at p */
static void note_str(char *p, unsigned char n)
{
    if (!n) {
        strcpy(p, "---");
        return;
    }
    --n;
    p[0] = note_names[2 * (n % 12)];
    p[1] = note_names[2 * (n % 12) + 1];
    p[2] = (char)('0' + n / 12);
    p[3] = 0;
}

#ifdef SIDP_LOG
/* the cost of the panel's parts (the emulator's cycle counter at $9FB8) */
static unsigned long m_t0, m_sum[5];
static unsigned long mcyc(void)
{
    unsigned long v = *(volatile unsigned char *)0x9FB8;
    v |= (unsigned long)*(volatile unsigned char *)0x9FB9 << 8;
    v |= (unsigned long)*(volatile unsigned char *)0x9FBA << 16;
    v |= (unsigned long)*(volatile unsigned char *)0x9FBB << 24;
    return v;
}
#define M0() (m_t0 = mcyc())
#define M1(k) (m_sum[k] += mcyc() - m_t0)
void viz_stats(void)
{
    static const char *const names[5] = { "RENDER", "WRITEROW", "VOICES", "FILTER", "TRACKER" };
    unsigned char k;
    for (k = 0; k < 5; ++k)
        LOGN(names[k], m_sum[k]);
}
#else
#define M0()
#define M1(k)
#endif

#define COL(v)     (2 + 26 * (v))
static const unsigned char scope_col[3] = { C_V1, C_V2, C_V3 };

/* the last values drawn (0xFF.. : draw again) */
static unsigned char l_note[3], l_ctrl[3], l_ad[3], l_sr[3], l_env[3], l_pwn[3];
static unsigned int l_pw[3], l_freq[3];
static unsigned char l_f[4];
static unsigned char next_scope, filter_turn;
static char s[40];

void viz_reset(void)
{
    memset(l_note, 0xFF, 3);
    memset(l_ctrl, 0xFF, 3);
    memset(l_ad, 0xFF, 3);
    memset(l_sr, 0xFF, 3);
    memset(l_pw, 0xFF, 6);
    memset(l_freq, 0xFF, 6);
    memset(l_f, 0xFF, 4);
    /* (l_env, l_pwn: the bars' lit cards, kept: the colour map shows them) */
}

static void scope(unsigned char v)
{
    const unsigned char *r = sid + 7 * v;
    unsigned char lv = playing && !paused ? env_hi[v] : 0;
    unsigned int f = r[0] | (unsigned int)r[1] << 8, y = V_SCOPE * 8;
    if (!(r[4] & 0xF0))
        lv = 0;
    sc_level = (unsigned char)(((unsigned int)lv * 17) >> 8);
    sc_ctrl = r[4];
    sc_pw = (unsigned char)((r[3] << 4) | (r[2] >> 4));
    /* the phase steps by the frequency / 4 (sidplay.s), low notes an octave
       or more up so that a cycle fits the scope */
    f >>= 2;
    if (f < 0x80)
        f = 0x80;
    while (f < 0x300)
        f <<= 1;
    sc_step = f;
    M0();
    scope_render(v);
    M1(0);
    M0();
    scope_blit(y * 80 + COL(v));
    M1(1);
}

/* a bar in the colour map from n lit cards to m: the cards that change, a
   colour's run at a time (zone gives a card's lit colour) */
static unsigned char env_zone(unsigned char i) { return i < 12 ? C_GREEN : i < 17 ? C_YELLOW : C_RED; }
static unsigned char pw_v;
static unsigned char pw_zone(unsigned char i) { (void)i; return scope_col[pw_v]; }

static void bar_to(unsigned char x, unsigned char y, unsigned char a, unsigned char n, unsigned char (*zone)(unsigned char))
{
    unsigned char b, z, on = n > a;
    unsigned char from = on ? a : n, to = on ? n : a;
    while (from < to) {
        z = zone(from);
        b = from;
        while (b < to && zone(b) == z)
            ++b;
        ColorRect(x + from, b - from, y, 1, on ? z : C_ENV_OFF);
        from = b;
    }
}

/* a row of flags: text with each flag's characters + 128 (reversed) when
   its bit is set; bit[i] the bit of the flag at text position at[i] */
static void flags(unsigned char x, unsigned char y, const char *t, unsigned char n, unsigned char c,
                  const unsigned char *at, const unsigned char *len, const unsigned char *bit, unsigned char k)
{
    unsigned char i, j;
    memcpy(s, t, n);
    s[n] = 0;
    for (i = 0; i < k; ++i)
        if (c & bit[i])
            for (j = 0; j < len[i]; ++j)
                s[at[i] + j] |= 0x80;
    cards(x, y * 8, s, n, 0);
}
static const unsigned char w_at[7] = { 0, 4, 8, 12, 16, 19, 22 }, w_len[7] = { 3, 3, 3, 3, 2, 2, 2 };
static const unsigned char w_bit[7] = { 0x10, 0x20, 0x40, 0x80, 0x01, 0x02, 0x04 };
static const unsigned char m_at[4] = { 0, 3, 6, 9 }, m_len[4] = { 2, 2, 2, 4 };
static const unsigned char m_bit[4] = { 0x10, 0x20, 0x40, 0x80 };
static const unsigned char r_at[4] = { 0, 2, 4, 6 }, r_len[4] = { 1, 1, 1, 3 };
static const unsigned char r_bit[4] = { 1, 2, 4, 8 };

static void voice(unsigned char v, unsigned char slot)
{
    const unsigned char *r = sid + 7 * v;
    unsigned char c = r[4], n, lv, x = COL(v);
    unsigned int f = r[0] | (unsigned int)r[1] << 8;
    /* the note: while the gate is on or the envelope still sounds */
    n = 0;
    if (playing && ((c & 1) || env_hi[v]))
        n = note_index(f);
    if (n != l_note[v]) {
        l_note[v] = n;
        note_str(s, n);
        cards(x + 20, V_HEAD * 8 + 4, s, 3, 0);
    }
    if (slot && c != l_ctrl[v]) {
        l_ctrl[v] = c;
        flags(x, V_WAVE, "TRI SAW PUL NOI GT SY RM", 24, c, w_at, w_len, w_bit, 7);
    }
    /* the level: the model's, voice 3 the SID's own ENV3 when the card
       reads it back (sidplay.s); none without a waveform or with the
       test bit */
    lv = env_hi[v];
    if (v == 2 && (card_status & 1))
        lv = sid[0x1C];
    if (!playing || !(c & 0xF0) || (c & 0x08))
        lv = 0;
    lv = (unsigned char)(((unsigned int)lv * 20 + 127) / 255);
    if ((slot || !lv) && lv != l_env[v]) {      /* (a voice a pass; silence at once) */
        bar_to(x + 4, V_ENV, l_env[v], lv, env_zone);
        l_env[v] = lv;
    }
}

/* the ADSR graph: attack up, decay to the sustain level, a while at it,
   release down (each rate's 0-15 as 2-24 pixels) */
#define AG_Y0      (V_TEXT * 8 - 4)
#define AG_Y1      (V_TEXT * 8 + 23)
static void adsr_graph(unsigned char v, unsigned char ad, unsigned char sr)
{
    unsigned int x = (COL(v) + V_GRAPH) * 8 + 3, y0 = AG_Y0 + 3, y1 = AG_Y1 - 3, ys, x1;
    clear(x - 2, AG_Y0 + 1, x + 82, AG_Y1 - 1);
    ys = y0 + ((15 - (sr >> 4)) * (y1 - y0)) / 15;
    x1 = x + 2 + ((ad >> 4) * 3) / 2;
    WDrawLine(DRAW_INK, x, y1, x1, y0);
    x = x1 + 2 + ((ad & 15) * 3) / 2;
    WDrawLine(DRAW_INK, x1, y0, x, ys);
    WDrawLine(DRAW_INK, x, ys, x + 10, ys);
    x1 = x + 10 + 2 + ((sr & 15) * 3) / 2;
    WDrawLine(DRAW_INK, x + 10, ys, x1, y1);
}

/* the voice's slower parts (a voice a pass, with its scope): ADSR and its
   graph, the pulse width and its bar, the frequency */
static void voice_text(unsigned char v)
{
    const unsigned char *r = sid + 7 * v;
    unsigned char x = COL(v), n;
    unsigned int f = r[0] | (unsigned int)r[1] << 8, pw = (r[3] & 15) << 8 | r[2];
    if (r[5] != l_ad[v] || r[6] != l_sr[v]) {
        l_ad[v] = r[5];
        l_sr[v] = r[6];
        strcpy(s, "ADSR ");
        hex(s + 5, (unsigned int)r[5] << 8 | r[6], 4);
        cards(x, V_TEXT * 8, s, 12, 0);
        adsr_graph(v, r[5], r[6]);
    }
    if (pw != l_pw[v]) {
        l_pw[v] = pw;
        strcpy(s, "PW    ");
        hex(s + 6, pw, 3);
        cards(x, (V_TEXT + 1) * 8, s, 12, 0);
        n = (unsigned char)((pw * 5) >> 10);    /* 0-19 of the bar's 20 cards */
        if (pw)
            ++n;
        if (n != l_pwn[v]) {
            pw_v = v;
            bar_to(x + 4, V_PW, l_pwn[v], n, pw_zone);
            l_pwn[v] = n;
        }
    }
    if (f != l_freq[v]) {
        unsigned long hz10 = ((unsigned long)f * (t_ntsc ? 1248 : 1203)) >> 11;
        char *p;
        l_freq[v] = f;
        hex(s, f, 4);
        s[4] = ' ';
        p = dec(s + 5, (unsigned int)(hz10 / 10));
        if (hz10 < 10000) {             /* (a tenth below 1000 Hz) */
            *p++ = '.';
            *p++ = (char)('0' + hz10 % 10);
        }
        strcpy(p, "Hz");
        cards(x, (V_TEXT + 2) * 8, s, 12, 0);
    }
}

static void bar(unsigned char x, unsigned char y, unsigned char w, unsigned char n, unsigned char c)
{
    if (n)
        ColorRect(x, n, y, 1, c);
    if (n < w)
        ColorRect(x + n, w - n, y, 1, C_ENV_OFF);
}

/* the filter's response: low, band and high pass around the cutoff (x),
   the resonance a peak there; a line through 25 points 8 pixels apart */
#define FG_COL     53           /* the box: cards 53-76, 26 rows from y 413 */
#define FG_Y0      (F_ROW1 * 8 - 3)
#define FG_H       26
static unsigned char resp(unsigned char x, unsigned char cx, unsigned char mode, unsigned char res)
{
    unsigned char d = x > cx ? x - cx : cx - x, r = 0, t;
    if (mode & 0x10)                    /* low pass */
        r = x <= cx ? 64 : d >= 48 ? 0 : 64 - d - (d >> 2) - (d >> 4);
    if (mode & 0x40) {                  /* high pass */
        t = x >= cx ? 64 : d >= 48 ? 0 : 64 - d - (d >> 2) - (d >> 4);
        if (t > r)
            r = t;
    }
    if (mode & 0x20) {                  /* band pass */
        t = d >= 36 ? 0 : 64 - ((d * 7) >> 2);
        if (t > r)
            r = t;
    }
    if (d < 16)
        r += (res * (16 - d)) >> 3;
    return r;
}

static void filter_graph(unsigned int cut, unsigned char res, unsigned char mode)
{
    unsigned char cx = (unsigned char)((cut * 3) >> 5);  /* 0-191 */
    unsigned char p[26], i, k, a, b, *t = sc_tab;
    for (i = 0; i <= 24; ++i)           /* rows 1-24 of the 26 the box holds */
        p[i] = (mode & 0x70) ? (unsigned char)(24 - ((resp((unsigned char)(i * 8), cx, mode, res) * 15) >> 6)) : 6;
    p[25] = p[24];
    /* 95 samples from x 2, 2 apart: a quarter, a half, three quarters of
       the way to the next point, then the next point */
    for (k = 0; k < 24; ++k) {
        a = p[k];
        b = p[k + 1];
        *t++ = (unsigned char)((a + a + a + b) >> 2);
        *t++ = (unsigned char)((a + b) >> 1);
        *t++ = (unsigned char)((a + b + b + b) >> 2);
        if (k < 23)
            *t++ = b;
    }
    curve_render();
    blit_rows = FG_H;
    scope_blit((unsigned int)FG_Y0 * 80 + FG_COL);
    blit_rows = 0;
}

static void filter(void)
{
    unsigned int cut = (unsigned int)sid[0x16] << 3 | (sid[0x15] & 7);
    unsigned char c, g = 0;
    if (sid[0x15] != l_f[0] || sid[0x16] != l_f[1]) {
        l_f[0] = sid[0x15];
        l_f[1] = sid[0x16];
        hex(s, cut, 3);
        cards(16, F_ROW1 * 8, s, 3, 0);
        bar(20, F_ROW1, 24, (unsigned char)((cut * 3) >> 8), C_PROG);
        g = 1;
    }
    c = sid[0x17];
    if (c != l_f[2]) {
        l_f[2] = c;
        hex(s, c >> 4, 1);
        cards(49, F_ROW1 * 8, s, 1, 0);
        flags(27, F_ROW2, "1 2 3 EXT", 9, c, r_at, r_len, r_bit, 4);
        g = 1;
    }
    c = sid[0x18];
    if (c != l_f[3]) {
        g |= (c ^ l_f[3]) & 0x70;
        l_f[3] = c;
        flags(7, F_ROW2, "LP BP HP 3OFF", 13, c, m_at, m_len, m_bit, 4);
        hex(s, c & 15, 1);
        cards(41, F_ROW2 * 8, s, 1, 0);
        bar(43, F_ROW2, 8, (unsigned char)(((c & 15) + 1) >> 1), C_GREEN);
    }
    if (g)
        filter_graph(cut, sid[0x17] >> 4, sid[0x18]);
}

void viz_frame(void)
{
    unsigned char v;
    for (v = 0; v < 3; ++v) {
        unsigned char x = COL(v);
        ColorRect(x, V_COLW, V_HEAD, 2, C_BAR);
        strcpy(sb, "Voice 1");
        sb[6] = (char)('1' + v);
        currentMode = SET_BOLD;
        WPutString(sb, x * 8 + 4, V_HEAD * 8 + 11);
        currentMode = 0;
        ColorRect(x, V_COLW, V_SCOPE, V_SCOPE_H / 8, scope_col[v]);
        cards(x, V_ENV * 8, "ENV", 3, 0);
        cards(x, V_PW * 8, "PW", 3, 0);
        ColorRect(x + 4, 20, V_ENV, 2, C_ENV_OFF);
        l_env[v] = l_pwn[v] = 0;
        WFrameRectangle(0xFF, (x + V_GRAPH) * 8, AG_Y0, (x + V_COLW) * 8 - 1, AG_Y1);
    }
    WHorizontalLine(0xFF, VP_L, VP_R, V_HEAD * 8 + 16);
    WHorizontalLine(0xFF, VP_L, VP_R, F_ROW1 * 8 - 5);
    cards(2, F_ROW1 * 8, "FILTER", 6, 0);
    cards(9, F_ROW1 * 8, "CUTOFF", 6, 0);
    cards(45, F_ROW1 * 8, "RES", 3, 0);
    cards(2, F_ROW2 * 8, "MODE", 4, 0);
    cards(21, F_ROW2 * 8, "ROUTE", 5, 0);
    cards(37, F_ROW2 * 8, "VOL", 3, 0);
    WHorizontalLine(0xFF, FG_COL * 8, FG_COL * 8 + 191, FG_Y0 + FG_H);     /* (the box's bottom: the curve's rows above it) */
    viz_reset();
    for (v = 0; v < 3; ++v) {
        scope(v);
        voice_text(v);
    }
}

/*---------------------------------------------------------------
  the tracker: rows of the notes that started (sidplay.s's tracker_row),
  written down the page and round again, the newest on the highlight
 ---------------------------------------------------------------*/
#define TRK_ROWS   24
#define TRK_TOP    9            /* card rows 9-32 */
static unsigned char trk[TRK_ROWS][9];  /* per voice: note, control, pulse width's top 8 bits */
static unsigned char trk_no[TRK_ROWS];
static unsigned char trk_n;             /* rows so far (the next one's number) */
static unsigned char live_gate[3], live_new[3], lt_note[3];
static unsigned int lt_freq[3];
static unsigned char trk_frames;

static void trk_row_draw(unsigned char i)
{
    unsigned char v, *c = trk[i];
    char *p = s;
    hex(p, trk_no[i], 2);
    p += 2;
    for (v = 0; v < 3; ++v, c += 3) {
        *p++ = ' ';
        *p++ = ' ';
        *p++ = ' ';
        if (c[0]) {
            note_str(p, c[0]);
            p[3] = ' ';
            p[4] = c[1] & 0x80 ? 'N' : c[1] & 0x40 ? 'P' : c[1] & 0x20 ? 'S' : c[1] & 0x10 ? 'T' : '.';
            p[5] = ' ';
            hex(p + 6, c[2], 2);
        } else
            memcpy(p, "--- . ..", 8);
        p += 8;
    }
    *p = 0;
    cards(3, (TRK_TOP + i) * 8, s, 37, 0);
}

static void trk_mark(unsigned char i, unsigned char on)
{
    unsigned char h = theme.hilite ? theme.hilite : C_PROG;
    ColorRect(2, 39, TRK_TOP + i, 1, on ? h : 0);
}

void trk_draw(void)
{
    unsigned char i;
    clear(LP_L + 1, LP_T + 1, LP_R - 1, LP_T + 15);
    currentMode = SET_BOLD;
    strcpy(sb, "Tracker");
    WPutString(sb, LIST_X + 4, LP_T + 12);
    currentMode = 0;
    strcpy(sb, "the notes as they start");
    WPutString(sb, LIST_X + 64, LP_T + 12);
    cards(3, 64, "ROW  VOICE 1    VOICE 2    VOICE 3", 37, 0);
    WHorizontalLine(0xFF, LIST_X, LP_R - 9, 72 - 1);
    for (i = 0; i < TRK_ROWS; ++i)
        if (i < trk_n)
            trk_row_draw(i);
    if (trk_n)
        trk_mark((unsigned char)((trk_n - 1) % TRK_ROWS), 1);
}

void trk_update(void)
{
    unsigned char v, i, *c, *r;
    if (!playing || paused)
        return;
    i = trk_n % TRK_ROWS;
    c = trk[i];
    trk_no[i] = trk_n;
    for (v = 0; v < 3; ++v, c += 3) {
        r = sid + 7 * v;
        c[0] = c[1] = c[2] = 0;
        if (live_new[v]) {
            live_new[v] = 0;
            c[0] = note_index(r[0] | (unsigned int)r[1] << 8);
            if (!c[0])
                c[0] = 1;
            c[1] = r[4];
            c[2] = (unsigned char)((r[3] << 4) | (r[2] >> 4));
        }
    }
    ++trk_n;
    if (view_tracker && !menuNumber) {
        trk_mark((unsigned char)((i + TRK_ROWS - 1) % TRK_ROWS), 0);
        trk_row_draw(i);
        trk_mark(i, 1);
        /* the row after it: empty, the sweep's gap */
        cards(3, (TRK_TOP + (i + 1) % TRK_ROWS) * 8, "", 37, 0);
    }
}

/* the pass: the registers just read (sid[]) */
void viz_update(void)
{
    static unsigned int last;
    unsigned char v, g;
    unsigned int f = IRQ_WORD(irq_frames);
    for (v = 0; v < 3; ++v) {         /* a note started? (seen between rows) */
        const unsigned char *r = sid + 7 * v;
        unsigned int fr = r[0] | (unsigned int)r[1] << 8;
        g = r[4] & 1;
        if (g && !live_gate[v])
            live_new[v] = 1;           /* the gate opened */
        live_gate[v] = g;
        if (fr != lt_freq[v]) {         /* another note while it sounds (an arpeggio) */
            lt_freq[v] = fr;
            fr = note_index(fr);
            if (fr != lt_note[v]) {
                lt_note[v] = (unsigned char)fr;
                if (g)
                    live_new[v] = 1;
            }
        }
    }
    scope(next_scope);
    M0();
    voice_text(next_scope);
    for (v = 0; v < 3; ++v)
        voice(v, v == next_scope);
    M1(2);
    if (next_scope == 2 && (++filter_turn & 1)) {      /* (every sixth pass: 5 a second) */
        M0();
        filter();
        M1(3);
    }
    if (++next_scope == 3)
        next_scope = 0;
    trk_frames += (unsigned char)(f - last);
    last = f;
    if (trk_frames >= 8) {
        trk_frames = 0;
        M0();
        trk_update();
        M1(4);
    }
}
